"""Write the shared cross-language fixtures in ``tests/fixtures``.

``encoding_v1.json`` lets the TypeScript encoder (``web/src/physics/encoding.ts``) and the
Python encoder be checked against the same numbers without committing full tensors: for each
case it stores per-channel sums over the grid and the values at a fixed set of pixels.

``postprocess_v1.json`` pins the domain check and the ensemble statistics (hotspot,
disagreement, field spread). The member tensors are an analytic pattern that both languages
generate (:func:`synthetic_members`), so no large arrays are committed.

``line_probe_v1.json`` holds the canonical plate solved on the ``fast`` mesh, in the layout of
the service's ``include_mesh`` payload, with line probes evaluated by ``physics.probe``. The
TypeScript probe (``web/src/lab/stress/probe.ts``) must reproduce them.

``convergence_v1.json`` holds the mesh convergence study of the canonical plate, with two
probes on the net section, in the layout of the service's ``physix.convergence/1`` levels and
fits. Solve times are zeroed so regenerating it is reproducible. The web study sheet renders it.

Run ``python -m data.fixtures`` after a deliberate encoding change and update consumers.
"""

from __future__ import annotations

import base64
import json
from pathlib import Path
from typing import Any

import numpy as np

from data.domain import DOMAIN, check_domain
from data.raster import (
    COLS,
    FEATURE_CHANNELS,
    RASTER_SCHEMA,
    ROWS,
    encode_features,
    fits_frame,
    solid_mask,
)
from model.ensemble import ensemble_statistics
from physics.case import case_from_dict
from physics.convergence import convergence_study
from physics.examples import bracket_dict, example_plate, plate_dict
from physics.mesh import MESH_PRESETS
from physics.probe import CONTAINMENT_TOL, SECTION_SAMPLES, probe_line, section_resultant
from physics.solver import SOLVER_NAME, SOLVER_VERSION, ElementField, solve

FIXTURE_PATH = Path("tests/fixtures/encoding_v1.json")
POSTPROCESS_PATH = Path("tests/fixtures/postprocess_v1.json")
LINE_PROBE_PATH = Path("tests/fixtures/line_probe_v1.json")
CONVERGENCE_PATH = Path("tests/fixtures/convergence_v1.json")
# A quarter and three quarters along the net section; the midpoint lies in the hole.
CONVERGENCE_PROBES = [(0.1, 0.02), (0.1, 0.06)]
LINE_PROBE_PRESET = "fast"
# The net section through the hole, and an oblique line that crosses the hole off-centre.
LINE_PROBES = {
    "net_section": {"a": [0.1, 0.0], "b": [0.1, 0.08], "n": 81},
    "oblique": {"a": [0.03, 0.012], "b": [0.17, 0.066], "n": 61},
}
SYNTHETIC_MEMBERS = 5


def fixture_cases() -> dict[str, dict[str, Any]]:
    three = plate_dict()
    three["geometry"] = {
        "width": 0.3,
        "height": 0.12,
        "holes": [
            {"x": 0.07, "y": 0.06, "radius": 0.02},
            {"x": 0.16, "y": 0.04, "radius": 0.012},
            {"x": 0.23, "y": 0.08, "radius": 0.015},
        ],
    }
    three["material"] = {"name": "aluminium_6061", "young": 68.9e9, "poisson": 0.33}
    return {"plate": plate_dict(), "bracket": bracket_dict(), "plate_three_holes": three}


def sample_pixels(n: int = 48, seed: int = 7) -> list[list[int]]:
    rng = np.random.default_rng(seed)
    rows = rng.integers(0, ROWS, n)
    cols = rng.integers(0, COLS, n)
    # Corners pin down orientation (row 0 at the top).
    pix = [[0, 0], [0, COLS - 1], [ROWS - 1, 0], [ROWS - 1, COLS - 1]]
    return pix + [[int(r), int(c)] for r, c in zip(rows, cols, strict=True)]


def build_fixture() -> dict[str, Any]:
    pixels = sample_pixels()
    cases = []
    for name, data in fixture_cases().items():
        feats = encode_features(case_from_dict(data)).astype(np.float64)
        cases.append(
            {
                "name": name,
                "case": data,
                "channel_sums": [float(feats[c].sum()) for c in range(feats.shape[0])],
                "values": [
                    [float(feats[c, r, k]) for c in range(feats.shape[0])] for r, k in pixels
                ],
            }
        )
    return {
        "schema": RASTER_SCHEMA,
        "rows": ROWS,
        "cols": COLS,
        "channels": list(FEATURE_CHANNELS),
        "pixels": pixels,
        "tolerance": {"value_abs": 1e-4, "sum_rel": 1e-4},
        "provenance": "generated by python -m data.fixtures from physics.examples",
        "cases": cases,
    }


def synthetic_members(k_members: int = SYNTHETIC_MEMBERS) -> np.ndarray:
    """Analytic unit-traction members ``(K, 6, ROWS, COLS)``; mirrored in TypeScript.

    T[k,c,i,j] = sin(0.11(c+1)i + 0.07j) + 0.5cos(0.05j(c+1)) + 0.04k sin(0.3i + 0.2j)
    """
    i = np.arange(ROWS)[:, None].astype(np.float64)
    j = np.arange(COLS)[None, :].astype(np.float64)
    out = np.empty((k_members, 6, ROWS, COLS), dtype=np.float64)
    for k in range(k_members):
        for c in range(6):
            out[k, c] = (
                np.sin(0.11 * (c + 1) * i + 0.07 * j)
                + 0.5 * np.cos(0.05 * j * (c + 1))
                + 0.04 * k * np.sin(0.3 * i + 0.2 * j)
            )
    return out.astype(np.float32)


def domain_cases() -> dict[str, dict[str, Any]]:
    cases = fixture_cases()
    soft = plate_dict()
    soft["material"] = {"name": "custom", "young": 1e9, "poisson": 0.45}
    crowded = plate_dict()
    crowded["geometry"]["holes"] = [
        {"x": 0.04, "y": 0.04, "radius": 0.01},
        {"x": 0.08, "y": 0.04, "radius": 0.01},
        {"x": 0.12, "y": 0.04, "radius": 0.01},
        {"x": 0.16, "y": 0.04, "radius": 0.01},
    ]
    edge = plate_dict()
    edge["geometry"]["holes"] = [{"x": 0.1, "y": 0.016, "radius": 0.012}]
    tall = bracket_dict()
    tall["geometry"]["height"] = 0.15
    cases.update(poisson_out=soft, four_holes=crowded, hole_near_edge=edge, bracket_tall=tall)
    return cases


def build_postprocess_fixture() -> dict[str, Any]:
    members = synthetic_members()
    out = []
    for name, data in domain_cases().items():
        case = case_from_dict(data)
        domain = check_domain(case)
        entry: dict[str, Any] = {"name": name, "case": data, "domain": domain.to_dict()}
        if fits_frame(case):
            mask = solid_mask(case)
            res = ensemble_statistics(members * mask, mask, case)
            entry["statistics"] = {
                "hotspot": res.hotspot,
                "member_hotspots": [float(v) for v in res.member_hotspots],
                "disagreement": res.disagreement,
                "field_spread": res.field_spread,
                "mask_pixels": int(mask.sum()),
            }
        out.append(entry)
    return {
        "schema": "physix.postprocess-fixture/1",
        "domain": DOMAIN,
        "members": SYNTHETIC_MEMBERS,
        "pattern": synthetic_members.__doc__.strip().splitlines()[-1].strip(),
        "tolerance": {"rel": 1e-4},
        "provenance": "generated by python -m data.fixtures; members are multiplied by the mask",
        "cases": out,
    }


def _b64(array: np.ndarray, dtype: Any) -> str:
    return base64.b64encode(np.ascontiguousarray(array, dtype=dtype).tobytes()).decode()


def decode_mesh(mesh: dict[str, Any]) -> ElementField:
    """The element field a client sees after decoding an ``include_mesh`` payload."""
    points = np.frombuffer(base64.b64decode(mesh["points"]), dtype="<f4").reshape(-1, 2)
    triangles = np.frombuffer(base64.b64decode(mesh["triangles"]), dtype="<i4").reshape(-1, 3)
    stress = np.frombuffer(base64.b64decode(mesh["stress"]), dtype="<f4").reshape(-1, 3, 3)
    return ElementField(
        points.astype(np.float64), triangles.astype(np.int64), stress.astype(np.float64)
    )


def _finite(values: np.ndarray) -> list[float | None]:
    return [float(v) if np.isfinite(v) else None for v in values]


def build_line_probe_fixture() -> dict[str, Any]:
    case = example_plate()
    sol = solve(case, MESH_PRESETS[LINE_PROBE_PRESET])
    mesh = {
        "points": _b64(sol.mesh.points, "<f4"),
        "triangles": _b64(sol.mesh.triangles, "<i4"),
        "stress": _b64(sol.stress.values, "<f4"),
        "n_nodes": int(sol.mesh.n_nodes),
        "n_triangles": int(len(sol.mesh.triangles)),
    }
    # Probe the decoded float32 mesh, exactly as the browser will see it.
    field = decode_mesh(mesh)
    probes = []
    for name, spec in LINE_PROBES.items():
        profile = probe_line(field, spec["a"], spec["b"], spec["n"])
        probes.append(
            {
                "name": name,
                **spec,
                "values": {k: _finite(profile[k]) for k in ("sxx", "syy", "txy", "von_mises")},
                "section_resultant": [
                    float(v)
                    for v in section_resultant(
                        case, probe_line(field, spec["a"], spec["b"], SECTION_SAMPLES)
                    )
                ],
            }
        )
    return {
        "schema": "physix.line-probe-fixture/1",
        "case": plate_dict(),
        "solver": {
            "name": SOLVER_NAME,
            "version": SOLVER_VERSION,
            "mesh_preset": LINE_PROBE_PRESET,
            "settings": MESH_PRESETS[LINE_PROBE_PRESET].to_dict(),
        },
        "applied_force": list(case.resultant_force()),
        "containment_tolerance": CONTAINMENT_TOL,
        "tolerance": {"value_rel_peak": 1e-6, "force_rel": 1e-6},
        "mesh": mesh,
        "probes": probes,
        "provenance": "generated by python -m data.fixtures from physics.examples.plate_dict",
    }


def build_convergence_fixture() -> dict[str, Any]:
    study = convergence_study(example_plate(), probes=CONVERGENCE_PROBES).to_dict()
    for level in study["levels"]:
        level["solve_ms"] = 0.0
    return {
        "schema": "physix.convergence-fixture/1",
        "case": plate_dict(),
        "solver": {"name": SOLVER_NAME, "version": SOLVER_VERSION, "element": "P2 triangle"},
        "presets": {name: MESH_PRESETS[name].to_dict() for name in MESH_PRESETS},
        "study": study,
        "provenance": (
            "generated by python -m data.fixtures from physics.examples.plate_dict with "
            "physics.convergence.convergence_study; solve_ms zeroed"
        ),
    }


def main() -> None:
    FIXTURE_PATH.parent.mkdir(parents=True, exist_ok=True)
    outputs = {
        FIXTURE_PATH: build_fixture(),
        POSTPROCESS_PATH: build_postprocess_fixture(),
        LINE_PROBE_PATH: build_line_probe_fixture(),
        CONVERGENCE_PATH: build_convergence_fixture(),
    }
    for path, payload in outputs.items():
        # LF on every platform, so regenerating on Windows leaves unchanged files untouched.
        path.write_text(json.dumps(payload, indent=1) + "\n", encoding="utf-8", newline="\n")
    print(f"wrote {', '.join(str(path) for path in outputs)}")


if __name__ == "__main__":
    main()
